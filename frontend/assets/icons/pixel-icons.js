// cores dos ícones coloridos
const PALETTES = {
  coinColor: { o: "#b9800e", y: "#ffc23d", w: "#fff1c4", d: "#e5a21f" },
}

// Junta pixels vizinhos da mesma linha num retângulo só (SVG menor)
function gridToRects(grid, palette = {}) {
  let rects = ""
  grid.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (ch === ".") { x++; continue }
      let end = x
      while (end < row.length && row[end] === ch) end++
      const fill = ch === "#" ? "currentColor" : (palette[ch] ?? "currentColor")
      rects += `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${fill}"/>`
      x = end
    }
  })
  return rects
}

const cache = {}

// pixelIcon("coin") -> string <svg> pronta para innerHTML
export function pixelIcon(name, { size = 18, label = "", className = "" } = {}) {
  const grid = GRIDS[name]
  if (!grid) return ""
  cache[name] ??= gridToRects(grid, PALETTES[name])
  const a11y = label ? `role="img" aria-label="${label}"` : `aria-hidden="true"`
  return `<svg class="px-icon ${className}" viewBox="0 0 9 9" width="${size}" height="${size}" shape-rendering="crispEdges" ${a11y}>${cache[name]}</svg>`
}

